const linkShape = z.custom<BlenderLink>((v) => {
  const l = v as BlenderLink;
  return !!l && typeof l.id === "string" && (l.origin === "effect" || l.origin === "linked") && typeof l.compId === "string";
}, { message: "Not a valid Blender link." });

export const blenderSet = defineOp({
  type: "blender.set",
  title: "Blender link",
  description: "Add or replace a Blender job (an effect simulated in Blender, or a linked .blend) in the project.",
  args: z.object({ link: linkShape }),
  apply: (d, a) => {
    const all = ((d as { blenderLinks?: Record<Id, BlenderLink> }).blenderLinks ??= {});
    all[a.link.id] = a.link as never;
  },
});

export const blenderRemove = defineOp({
  type: "blender.remove",
  title: "Remove Blender link",
  description: "Remove a Blender job from the project (its rendered video stays as media).",
  args: z.object({ linkId: z.string() }),
  apply: (d, a) => {
    const all = (d as { blenderLinks?: Record<Id, BlenderLink> }).blenderLinks;
    if (!all?.[a.linkId]) throw new OpError("That Blender link no longer exists.");
    delete all[a.linkId];
  },
});

export const blenderOps = [blenderSet, blenderRemove];

