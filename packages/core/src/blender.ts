/**
 * Blender integration, the model side.
 *
 * Before Effects keeps a link per Blender job in the project: an effect it generated (smoke, fire,
 * liquid, cloth — physical simulations Blender is good at), or a person's own .blend linked in. To
 * build or render one it hands Blender an exchange file (below): the show camera — so Blender's
 * render lines up exactly with the canvas — the building's solids with the photo, the effect's
 * emitter and domain, the frame range, and who simulates each object:
 *
 *   owner "before-effects"  moved by keyframes or by motion Before Effects already prepared with
 *                           its own physics (Rapier); Blender plays it back and treats it as an
 *                           obstacle — it never simulates it.
 *   owner "blender"         simulated by Blender (smoke, fire, liquid, cloth).
 *
 * An object has exactly one owner. Blender renders the effect with the building as a holdout (it
 * hides what's behind it but isn't drawn), with a transparent background, and the result comes back
 * as an ordinary video layer that sits exactly on the canvas.
 *
 * Coordinates in the exchange are Before Effects' (metres; x right, y up, z toward the audience);
 * the Blender scripts convert to Blender's (z up).
 */
