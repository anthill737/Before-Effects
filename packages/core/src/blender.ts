export const EXCHANGE_VERSION = 1;

/** A closed solid as triangles (Before Effects coordinates), with photo coordinates per vertex. */
export interface ExchangeMesh {
  readonly verts: ReadonlyArray<readonly [number, number, number]>;
  readonly tris: ReadonlyArray<readonly [number, number, number]>;
  /** Photo texture coordinates (0..1, origin top-left of the canvas). */
  readonly uvs?: ReadonlyArray<readonly [number, number]>;
}

export interface ExchangeObject {
  readonly name: string;
  readonly owner: "before-effects" | "blender";
  /** obstacle: hides what's behind it and blocks the simulation · emitter / cloth: the simulated thing. */
  readonly role: "obstacle" | "emitter" | "cloth" | "ground" | "debris" | "backdrop";
  readonly mesh: ExchangeMesh;
  /** Photo on the front (for cloth that shows the photo; obstacles are holdouts). */
  readonly photo?: boolean;
  /** Played-back motion (owner before-effects): per frame from frame 1, [x,y,z, qx,qy,qz,qw]. */
  readonly motion?: ReadonlyArray<readonly number[]>;
  /**
   * Cloth only: vertices held by a handle, the handle's keyframes [frame, dx, dy, dz] (metres, from
   * where it starts), and the frame each held vertex lets go (parallel to `verts`; absent = held
   * throughout). The rest of the sheet is simulated and follows.
   */
  readonly pin?: { readonly verts: readonly number[]; readonly keys: ReadonlyArray<readonly [number, number, number, number]>; readonly release?: readonly number[] };
  /** Debris only: the frame it lets go, its push (m/s) and spin (radians/s, about x, y, z) then. */
  readonly release?: { readonly frame: number; readonly velocity: Vec3; readonly spin: Vec3 };
}

